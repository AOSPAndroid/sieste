import {readFileSync} from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const code=ts.transpileModule(readFileSync('app/climb-settings.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {readCyclingClimbSettings:read,saveCyclingClimbSettings:save}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
assert.deepEqual(read(),{mode:'steep',minGradePercent:3});
const records=new Map();
globalThis.window={localStorage:{getItem:key=>records.get(key)??null,setItem:(key,value)=>records.set(key,value)}};
save({mode:'whole',minGradePercent:6});
assert.deepEqual(read(),{mode:'whole',minGradePercent:6},'Device preference survives a new read');
save({mode:'steep',minGradePercent:4});
assert.deepEqual(read(),{mode:'steep',minGradePercent:4});
const key=[...records.keys()][0];
records.set(key,'{broken');assert.deepEqual(read(),{mode:'steep',minGradePercent:3});
records.set(key,JSON.stringify({mode:'unexpected',minGradePercent:100}));assert.deepEqual(read(),{mode:'steep',minGradePercent:3});
Object.defineProperty(window,'localStorage',{get(){throw new Error('Storage blocked')}});
assert.doesNotThrow(()=>save({mode:'steep',minGradePercent:5}));
assert.deepEqual(read(),{mode:'steep',minGradePercent:3});
delete globalThis.window;
console.log('Cycling climb preferences persist mode/cutoff and recover from malformed or blocked device storage.');
