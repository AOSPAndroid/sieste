import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import sharp from 'sharp';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
/** Lossless artwork conversion. Geometry and alpha masks remain unchanged. */
export async function packageApprovedArt(){
 const source=path.join(root,'app/original-share-art.json');
 const atlas=JSON.parse(await readFile(source,'utf8'));
 const directory=path.join(root,'public/share-assets/art');await mkdir(directory,{recursive:true});
 const converted=new Map();
 for(const section of ['glyphs','groups','icons'])for(const items of Object.values(atlas[section]))for(const item of Object.values(items))for(const key of ['png','faceMask']){
  const original=item[key];if(!original.startsWith('data:image/png;base64,'))continue;
  if(!converted.has(original)){
   const png=Buffer.from(original.split(',')[1],'base64'),webp=await sharp(png).webp({lossless:true,effort:6}).toBuffer();
   const name=createHash('sha256').update(webp).digest('hex').slice(0,20)+'.webp';
   await writeFile(path.join(directory,name),webp);converted.set(original,'/share-assets/art/'+name);
  }
  item[key]=converted.get(original);
 }
 await writeFile(source,JSON.stringify(atlas)+'\n');
 for(const kind of ['running','cycling','recovery']){
  const manifest=Object.fromEntries(['glyphs','groups','icons'].map(section=>[section,atlas[section][kind]]));
  await writeFile(path.join(directory,kind+'.json'),JSON.stringify(manifest)+'\n');
 }
 return converted.size;
}
export async function writeShareAssetIndex(){
 const index={};
 for(const folder of ['fonts','art'])for(const file of await readdir(path.join(root,'public/share-assets',folder))){
  if(!file.endsWith('.json'))continue;
  const data=await readFile(path.join(root,'public/share-assets',folder,file)),hash=createHash('sha256').update(data).digest('hex').slice(0,12);
  index[`/share-assets/${folder}/${file}`]=`/share-assets/${folder}/${file}?v=${hash}`;
 }
 await writeFile(path.join(root,'app/share-asset-index.ts'),'// Generated by scripts/package-share-assets.mjs after artwork/font changes.\nexport const shareAssetPaths:Record<string,string>='+JSON.stringify(index)+';\n');
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 if(!process.argv.includes('--index'))console.log('Packaged '+await packageApprovedArt()+' lossless artwork files');
 await writeShareAssetIndex();
}
