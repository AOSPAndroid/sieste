import {readFileSync} from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const source=ts.transpileModule(readFileSync(new URL('../app/performance-math.ts',import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {mean,quantile,pearson,bestWindows,normalizedPower,sessionTotals}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(mean([null,undefined,NaN,Infinity]),null);
assert.equal(mean([0,10,null]),5);
assert.equal(quantile([0,10,20,30],.5),15);
assert.equal(pearson([1,2,3,4].map(x=>({x,y:x}))),null);
assert.equal(pearson([1,2,3,4,5].map(x=>({x,y:7}))),null);
assert.ok(Math.abs(pearson([1,2,3,4,5].map(x=>({x,y:-2*x})))+1)<1e-10);
assert.deepEqual(bestWindows([100,200,300,400],2,[4]),[{seconds:4,value:350,start:4}]);
assert.deepEqual(bestWindows([100,null,300,400],2,[6]),[]);
assert.deepEqual(bestWindows([100,null,300,400],2,[4]),[{seconds:4,value:350,start:4}]);
assert.deepEqual(bestWindows([100,200,300,400],2,[5]),[{seconds:6,value:300,start:2}]);
assert.equal(normalizedPower(Array(600).fill(250),1),250);
assert.equal(normalizedPower([250,null,...Array(600).fill(250)],1),null);
assert.equal(normalizedPower(Array(600).fill(250),0),null);
assert.equal(normalizedPower(Array(20).fill(250),1),null);
const blocks=sessionTotals([{summary:{duration:3600,distance:10000,heartrate:120}},{summary:{duration:1800,heartrate:160}},{summary:{calories:300}}]);
assert.equal(blocks.duration,5400);assert.equal(blocks.durationCoverage,2);assert.equal(blocks.distance,10000);assert.equal(blocks.heartrate,140);assert.equal(blocks.vo2max,null);
assert.equal(sessionTotals([]).duration,null);
console.log('Performance math: complete rolling windows, gaps, sample-duration rounding, normalized power, missing data, quantiles, correlations and block coverage passed.');
